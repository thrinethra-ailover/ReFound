"""Generate ReFound's offline Wordnet lexicon from Open English Wordnet 2025.

Source: https://en-word.net/static/english-wordnet-2025-json.zip
License: CC BY 4.0. The generated subset is committed with attribution in
supabase/OPEN_ENGLISH_WORDNET_NOTICE.md.
"""

from __future__ import annotations

import json
import re
import urllib.request
import zipfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE_URL = "https://en-word.net/static/english-wordnet-2025-json.zip"
SOURCE_ZIP = ROOT / "oewn-2025-json.zip"
MIGRATION_OUT = ROOT / "supabase/migrations/0018_open_english_wordnet.sql"
TYPESCRIPT_OUT = ROOT / "src/lib/matching/openEnglishWordnetSynsets.ts"
ALIAS_MIGRATION = ROOT / "supabase/migrations/0012_expanded_offline_vocabulary.sql"

# Wordnet covers nouns, verbs, adjectives, and adverbs. These are the parts
# most useful for physical object reports and distinctive descriptions.
SOURCE_FILES = (
    "adj.all.json",
    "noun.artifact.json",
    "noun.attribute.json",
    "noun.object.json",
    "noun.possession.json",
    "noun.shape.json",
    "noun.substance.json",
    "noun.location.json",
)


def read_aliases() -> dict[str, str]:
    sql = ALIAS_MIGRATION.read_text(encoding="utf-8")
    return dict(re.findall(r"\('([^']+)','([^']+)'\)", sql))


def stem(word: str) -> str:
    if re.fullmatch(r"[a-z]{5,}ies", word):
        return word[:-3] + "y"
    if re.fullmatch(r"[a-z]{5,}(?:sses|xes|ches|shes)", word):
        return word[:-2]
    if re.fullmatch(r"[a-z]{5,}s", word) and not re.search(r"(?:ss|us|is)$", word):
        return word[:-1]
    if re.fullmatch(r"[a-z]{6,}ing", word):
        base = word[:-3]
        return base[:-1] if re.search(r"(.)\1$", base) else base
    if re.fullmatch(r"[a-z]{5,}ed", word):
        base = word[:-2]
        return base[:-1] if re.search(r"(.)\1$", base) else base
    return word


def main() -> None:
    if not SOURCE_ZIP.exists():
        print(f"Downloading Open English Wordnet 2025 from {SOURCE_URL}")
        urllib.request.urlretrieve(SOURCE_URL, SOURCE_ZIP)

    aliases = read_aliases()
    synset_words: dict[str, set[str]] = {}
    with zipfile.ZipFile(SOURCE_ZIP) as archive:
        for filename in SOURCE_FILES:
            payload = json.loads(archive.read(filename))
            for synset_id, synset in payload.items():
                words = set()
                for member in synset.get("members", []):
                    word = member.lower()
                    # The app tokenizer handles phrases as separate words;
                    # keep only single-word lexical entries here.
                    if not re.fullmatch(r"[a-z]{3,}", word):
                        continue
                    word = aliases.get(stem(word), stem(word))
                    if re.fullmatch(r"[a-z]{3,}", word):
                        words.add(word)
                if len(words) > 1:
                    synset_words[synset_id] = words

    word_synsets: dict[str, list[str]] = {}
    rows: list[tuple[str, str]] = []
    for synset_id, words in sorted(synset_words.items()):
        for word in sorted(words):
            word_synsets.setdefault(word, []).append(synset_id)
            rows.append((word, synset_id))

    migration = [
        "-- Open English Wordnet 2025 sense-based synonym groups for private ownership verification.",
        "-- Generated by scripts/build_oewn_lexicon.py from the official JSON release.",
        "-- See supabase/OPEN_ENGLISH_WORDNET_NOTICE.md for attribution and license.",
        "create table if not exists public.verification_wordnet_synsets (",
        "  word text not null check (word ~ '^[a-z]+$'),",
        "  synset_id text not null,",
        "  primary key (word, synset_id)",
        ");",
        "create index if not exists verification_wordnet_synsets_synset_word_idx",
        "  on public.verification_wordnet_synsets (synset_id, word);",
        "alter table public.verification_wordnet_synsets enable row level security;",
        "revoke all on public.verification_wordnet_synsets from public, anon, authenticated;",
        "",
    ]
    for start in range(0, len(rows), 500):
        batch = rows[start : start + 500]
        values = ",\n".join(
            f"  ('{word}', '{synset_id}')" for word, synset_id in batch
        )
        migration.extend(
            [
                "insert into public.verification_wordnet_synsets (word, synset_id) values",
                values,
                "on conflict do nothing;",
                "",
            ]
        )

    migration.extend(
        [
            "create or replace function public.verification_answers_match(p_claimed text, p_actual text)",
            "returns boolean",
            "language plpgsql",
            "stable",
            "set search_path = public",
            "as $$",
            "declare",
            "  v_claimed text[] := public.verification_tokens(p_claimed);",
            "  v_actual text[] := public.verification_tokens(p_actual);",
            "  v_used boolean[];",
            "  v_claim_index integer;",
            "  v_actual_index integer;",
            "  v_shared integer := 0;",
            "begin",
            "  if cardinality(v_claimed) = 0 or cardinality(v_actual) = 0 then return false; end if;",
            "  if v_claimed = v_actual then return true; end if;",
            "  if exists (",
            "    select 1 from unnest(v_claimed) c(token) join unnest(v_actual) a(token)",
            "    on (c.token='red' and a.token in ('blue','green','yellow','purple','orange','pink'))",
            "      or (a.token='red' and c.token in ('blue','green','yellow','purple','orange','pink'))",
            "      or (c.token='blue' and a.token in ('yellow','orange'))",
            "      or (a.token='blue' and c.token in ('yellow','orange'))",
            "      or (c.token='black' and a.token='white') or (c.token='white' and a.token='black')",
            "      or (c.token='left' and a.token='right') or (c.token='right' and a.token='left')",
            "      or (c.token='upper' and a.token='lower') or (c.token='lower' and a.token='upper')",
            "      or (c.token='front' and a.token='back') or (c.token='back' and a.token='front')",
            "      or (c.token='inside' and a.token='outside') or (c.token='outside' and a.token='inside')",
            "      or (c.token='small' and a.token='large') or (c.token='large' and a.token='small')",
            "      or (c.token='new' and a.token='old') or (c.token='old' and a.token='new')",
            "  ) then return false; end if;",
            "",
            "  v_used := array_fill(false, array[cardinality(v_actual)]);",
            "  -- First reserve exact token matches, then use shared Wordnet senses.",
            "  for v_claim_index in 1..cardinality(v_claimed) loop",
            "    select j into v_actual_index from generate_subscripts(v_actual, 1) as g(j)",
            "    where not v_used[j] and v_actual[j] = v_claimed[v_claim_index] limit 1;",
            "    if found then",
            "      v_used[v_actual_index] := true; v_shared := v_shared + 1;",
            "    end if;",
            "  end loop;",
            "  for v_claim_index in 1..cardinality(v_claimed) loop",
            "    if exists (select 1 from generate_subscripts(v_actual, 1) g(j)",
            "              where not v_used[j] and v_actual[j] = v_claimed[v_claim_index]) then continue; end if;",
            "    select j into v_actual_index",
            "    from generate_subscripts(v_actual, 1) as g(j)",
            "    where not v_used[j] and exists (",
            "      select 1 from public.verification_wordnet_synsets c",
            "      join public.verification_wordnet_synsets a using (synset_id)",
            "      where c.word = v_claimed[v_claim_index] and a.word = v_actual[j]",
            "    ) limit 1;",
            "    if found then",
            "      v_used[v_actual_index] := true; v_shared := v_shared + 1;",
            "    end if;",
            "  end loop;",
            "",
            "  if cardinality(v_claimed) = cardinality(v_actual) and v_shared = cardinality(v_claimed) then return true; end if;",
            "  if v_shared < 2 then return false; end if;",
            "  return v_shared::numeric / greatest(cardinality(v_claimed), cardinality(v_actual)) >= 0.6666666667;",
            "end;",
            "$$;",
            "revoke all on function public.verification_answers_match(text, text) from public, anon, authenticated;",
            "",
        ]
    )
    MIGRATION_OUT.write_text("\n".join(migration), encoding="utf-8")

    compact_json = json.dumps(word_synsets, separators=(",", ":"), ensure_ascii=True)
    TYPESCRIPT_OUT.write_text(
        "// Generated from Open English Wordnet 2025; see the repository notice for attribution.\n"
        "export const OPEN_ENGLISH_WORDNET_SYNSETS: Record<string, readonly string[]> = "
        f"JSON.parse(String.raw`{compact_json}`);\n",
        encoding="utf-8",
    )
    print(f"Generated {len(rows):,} word/synset pairs across {len(synset_words):,} synsets.")
    print(f"Migration: {MIGRATION_OUT.stat().st_size:,} bytes")
    print(f"TypeScript index: {TYPESCRIPT_OUT.stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
